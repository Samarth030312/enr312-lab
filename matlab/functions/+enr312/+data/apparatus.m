function A = apparatus(code)
%APPARATUS  The three rigs: run-id code, data folder, telemetry type, firmware.
%
%   A = enr312.data.apparatus('MOTOR')     % or 'TEMP', 'WATER'; no argument: all three
    all = struct( ...
        'code',   {'MOTOR', 'TEMP', 'WATER'}, ...
        'folder', {'dc_motor', 'temperature', 'water_level'}, ...
        'tel',    {'TEL', 'TTEL', 'LTEL'}, ...
        'sketch', {'motor', 'temperature', 'level'}, ...
        'name',   {'DC motor (RMCS-2303 + RMCS-5032)', 'Temperature (bulb, DHT11, SSR)', 'Water level (tank, pump, HC-SR04)'});
    if nargin == 0, A = all; return; end
    A = all(strcmpi({all.code}, code));
    assert(~isempty(A), 'enr312:data:apparatus', 'unknown apparatus %s (MOTOR, TEMP, WATER)', code);
end
