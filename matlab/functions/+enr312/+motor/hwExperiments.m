function E = hwExperiments()
%HWEXPERIMENTS  Hardware experiment library for the lab rig (RMCS-2303 + RMCS-5032).
%
%   E = enr312.motor.hwExperiments()
%
%   Each experiment is one or more runs. A run fixes the loop, controller and gains,
%   then plays a setpoint profile [t_s, setpoint] (output rpm for 'speed', output
%   degrees for 'position', measured from where the run starts) for 'duration' s.
%   ExperimentRunner plays them on the hardware; every run is saved as raw data.
%
%   Gains are tuned in simulation against the lab drive's MEASURED acceleration register
%   (5000, ramp ~50 output rpm/s): faster integral gains overshoot ~40 % because the
%   integrator winds up while the drive ramps.
%   Limits chosen for the 11.2 V battery: |speed| <= 120 rpm (motor free-running
%   maximum ~168 rpm at 11.2 V), position moves <= 1 revolution.

    E = struct('name', {}, 'id', {}, 'purpose', {}, 'runs', {});
    sp = @(ctrl, Kp, Ki, prof, dur) run('speed', ctrl, Kp, Ki, prof, dur);
    ps = @(ctrl, Kp, Ki, prof, dur) run('position', ctrl, Kp, Ki, prof, dur);

    add('Speed steps, open loop (drive only)', 'MOTOR-02', ...
        'Identify the drive + motor: ramp rate, settling, steady speed at 20...120 rpm.', ...
        sp('OL', 0, 0, [0 20; 3 40; 6 80; 9 120; 12 80; 15 40; 18 0], 20));
    add('Direction and reversal, open loop', 'MOTOR-02', ...
        'Positive command must give positive speed; reversal time through zero.', ...
        sp('OL', 0, 0, [0 30; 5 -30; 10 0], 12));
    add('Speed tracking, PI (Kp 0.3, Ki 1.5)', 'MOTOR-03', ...
        'Closed-loop speed control following setpoint changes.', ...
        sp('PI', 0.3, 1.5, [0 50; 5 100; 10 30; 15 0], 20));
    add('Speed P gain sweep (Kp 0.2 / 0.5 / 0.8)', 'MOTOR-05', ...
        'P alone leaves e_ss = r/(1+Kp); measure it for three gains.', ...
        [sp('P', 0.2, 0, [0 60], 8), sp('P', 0.5, 0, [0 60], 8), sp('P', 0.8, 0, [0 60], 8)]);
    add('Speed I only (Ki 1.0)', 'MOTOR-06', ...
        'Integral action removes the error, more slowly than PI.', ...
        sp('I', 0, 1.0, [0 60; 8 30], 16));
    add('Speed PI step, 60 rpm', 'MOTOR-07', ...
        'PI: fast reaction and zero steady-state error.', ...
        sp('PI', 0.3, 1.5, [0 60], 10));
    add('Position moves, P (Kp 0.3): 90, -90, 360 deg', 'MOTOR-04', ...
        'Closed-loop position control; zero steady-state error expected (plant integrates).', ...
        ps('P', 0.3, 0, [0 90; 6 -90; 12 360; 20 0], 26));
    add('Position P gain sweep (Kp 0.2 / 0.3 / 0.5)', 'MOTOR-05', ...
        'Rise time and overshoot versus Kp for a 90 deg step.', ...
        [ps('P', 0.2, 0, [0 90], 7), ps('P', 0.3, 0, [0 90], 7), ps('P', 0.5, 0, [0 90], 7)]);
    add('Position I only (Ki 0.1): expect oscillation', 'MOTOR-06', ...
        'Two integrators in the loop: the angle oscillates around the target.', ...
        ps('I', 0, 0.1, [0 45], 12));
    add('Position PI (Kp 0.3, Ki 0.03)', 'MOTOR-07', ...
        'PI on position: overshoot and a slow tail, little benefit over P.', ...
        ps('PI', 0.3, 0.03, [0 90], 12));

    function add(name, id, purpose, runs)
        E(end + 1) = struct('name', name, 'id', id, 'purpose', purpose, 'runs', runs);
    end
end

function r = run(loop, ctrl, Kp, Ki, profile, duration)
    r = struct('loop', loop, 'ctrl', ctrl, 'Kp', Kp, 'Ki', Ki, 'profile', profile, 'duration', duration);
end
